/**
 * Regenerates the server icon — `npm run icon`. Dependency-free: rasterizes
 * the shapes below with supersampling and encodes the PNG by hand.
 *
 * Outputs:
 *   assets/icon.svg   vector source of truth (same geometry)
 *   assets/icon.png   512px, referenced by server.json / README
 *   src/icon.ts       128px PNG as a data URI, served in MCP serverInfo.icons
 *
 * The design is original (equalizer bars on a dark tile) — it deliberately
 * does not use Spotify's logo, which their brand guidelines restrict.
 */
import { mkdirSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";
import { deflateSync } from "node:zlib";

const ROOT = join(dirname(fileURLToPath(import.meta.url)), "..");

const BG = [0x11, 0x18, 0x27];
const FG = [0x22, 0xc5, 0x5e];
const TILE_RADIUS = 0.22;
const BAR_WIDTH = 0.11;
/** [centre x, height] in unit coordinates; bars are vertically centred capsules. */
const BARS = [
  [0.26, 0.3],
  [0.42, 0.56],
  [0.58, 0.4],
  [0.74, 0.22],
];

function inRoundRect(x, y, x0, y0, x1, y1, r) {
  const cx = Math.min(Math.max(x, x0 + r), x1 - r);
  const cy = Math.min(Math.max(y, y0 + r), y1 - r);
  return (x - cx) ** 2 + (y - cy) ** 2 <= r * r;
}

const barRect = ([cx, h]) => [cx - BAR_WIDTH / 2, 0.5 - h / 2, cx + BAR_WIDTH / 2, 0.5 + h / 2];

function render(size, ss = 4) {
  const px = Buffer.alloc(size * size * 4);
  for (let py = 0; py < size; py++) {
    for (let pxl = 0; pxl < size; pxl++) {
      let tile = 0;
      let bar = 0;
      for (let sy = 0; sy < ss; sy++) {
        for (let sx = 0; sx < ss; sx++) {
          const x = (pxl + (sx + 0.5) / ss) / size;
          const y = (py + (sy + 0.5) / ss) / size;
          if (!inRoundRect(x, y, 0, 0, 1, 1, TILE_RADIUS)) continue;
          tile++;
          if (BARS.some((b) => inRoundRect(x, y, ...barRect(b), BAR_WIDTH / 2))) bar++;
        }
      }
      const i = (py * size + pxl) * 4;
      const mix = tile ? bar / tile : 0;
      for (let c = 0; c < 3; c++) px[i + c] = Math.round(BG[c] + (FG[c] - BG[c]) * mix);
      px[i + 3] = Math.round((tile / (ss * ss)) * 255);
    }
  }
  return px;
}

const CRC_TABLE = Array.from({ length: 256 }, (_, n) => {
  let c = n;
  for (let k = 0; k < 8; k++) c = c & 1 ? 0xedb88320 ^ (c >>> 1) : c >>> 1;
  return c >>> 0;
});

function crc32(buf) {
  let c = 0xffffffff;
  for (const b of buf) c = CRC_TABLE[(c ^ b) & 0xff] ^ (c >>> 8);
  return (c ^ 0xffffffff) >>> 0;
}

function chunk(type, data) {
  const body = Buffer.concat([Buffer.from(type, "ascii"), data]);
  const out = Buffer.alloc(body.length + 8);
  out.writeUInt32BE(data.length, 0);
  body.copy(out, 4);
  out.writeUInt32BE(crc32(body), body.length + 4);
  return out;
}

function png(size) {
  const rgba = render(size);
  const raw = Buffer.alloc(size * (size * 4 + 1)); // each row is prefixed with filter byte 0
  for (let y = 0; y < size; y++) rgba.copy(raw, y * (size * 4 + 1) + 1, y * size * 4, (y + 1) * size * 4);
  const ihdr = Buffer.alloc(13);
  ihdr.writeUInt32BE(size, 0);
  ihdr.writeUInt32BE(size, 4);
  ihdr.set([8, 6, 0, 0, 0], 8); // 8-bit RGBA
  return Buffer.concat([
    Buffer.from([0x89, 0x50, 0x4e, 0x47, 0x0d, 0x0a, 0x1a, 0x0a]),
    chunk("IHDR", ihdr),
    chunk("IDAT", deflateSync(raw, { level: 9 })),
    chunk("IEND", Buffer.alloc(0)),
  ]);
}

const hex = (rgb) => "#" + rgb.map((v) => v.toString(16).padStart(2, "0")).join("");
const n = (v) => +(v * 256).toFixed(2);
const svg =
  `<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 256 256">\n` +
  `  <rect width="256" height="256" rx="${n(TILE_RADIUS)}" fill="${hex(BG)}"/>\n` +
  BARS.map((b) => {
    const [x0, y0, x1, y1] = barRect(b);
    return `  <rect x="${n(x0)}" y="${n(y0)}" width="${n(x1 - x0)}" height="${n(y1 - y0)}" rx="${n(BAR_WIDTH / 2)}" fill="${hex(FG)}"/>\n`;
  }).join("") +
  `</svg>\n`;

const EMBED_SIZE = 128;
mkdirSync(join(ROOT, "assets"), { recursive: true });
writeFileSync(join(ROOT, "assets", "icon.svg"), svg);
writeFileSync(join(ROOT, "assets", "icon.png"), png(512));
writeFileSync(
  join(ROOT, "src", "icon.ts"),
  `// Generated by scripts/make-icon.mjs (npm run icon) — do not edit by hand.\n` +
    `export const ICON_SIZE = "${EMBED_SIZE}x${EMBED_SIZE}";\n` +
    `export const ICON_DATA_URI =\n  "data:image/png;base64,${png(EMBED_SIZE).toString("base64")}";\n`
);
console.log("Wrote assets/icon.svg, assets/icon.png, src/icon.ts");
